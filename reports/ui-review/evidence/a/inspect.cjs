const { chromium } = require('C:/Users/mridu/AppData/Local/npm-cache/_npx/9833c18b2d85bc59/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const dir = __dirname;
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/mridu/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe' });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const results = [];
  const capture = async (route, name) => {
    await page.goto('http://127.0.0.1:3000' + route, { waitUntil: 'domcontentloaded', timeout: 60000 });
    await page.waitForTimeout(1500);
    await page.screenshot({ path: path.join(dir, name + '.png'), fullPage: true });
    const data = await page.evaluate(() => ({ title: document.title, text: document.body.innerText, links: [...document.querySelectorAll('a')].map(a => ({text: a.innerText, href: a.getAttribute('href')})), width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
    results.push({route, name, ...data});
    console.log(name, page.url(), data.scrollWidth);
    fs.writeFileSync(path.join(dir, 'screens.json'), JSON.stringify(results, null, 2));
    return data;
  };
  await capture('/', 'home-desktop');
  const practice = await capture('/practice', 'practice-desktop');
  const practiceHref = practice.links.find(l => /^\/practice\//.test(l.href))?.href;
  if (practiceHref) await capture(practiceHref, 'practice-workspace-desktop');
  const oa = await capture('/oa', 'oa-desktop');
  const oaHref = oa.links.find(l => /^\/oa\//.test(l.href) && !l.href.includes('/results'))?.href;
  if (oaHref) await capture(oaHref, 'oa-workspace-desktop');
  await capture('/dashboard', 'dashboard-desktop');
  await capture('/assessment', 'assessment-desktop');
  await capture('/assessment/results', 'assessment-results-empty');
  await capture('/oa/results/review-nonexistent', 'oa-results-empty');
  await page.setViewportSize({width:390,height:844});
  await capture('/', 'home-phone');
  await capture('/practice', 'practice-phone');
  if (practiceHref) await capture(practiceHref, 'practice-workspace-phone');
  await capture('/oa', 'oa-phone');
  if (oaHref) await capture(oaHref, 'oa-workspace-phone');
  await capture('/dashboard', 'dashboard-phone');
  await browser.close();
})().catch(e => { console.error(e); process.exitCode = 1; });
